"""
Claude-powered MLOps remediation agent.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
WHAT IS AN AI AGENT?
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
A plain language model (like Claude) reads text and writes text.
An AGENT is a language model that can also take actions — and that is
exactly what we build here.

The actions are called TOOLS. We define four tools:
  1. get_drift_summary         — read the Evidently JSON and summarise it
  2. get_current_model_metrics — check the baseline model performance
  3. run_training              — retrain the model with new hyperparameters
  4. save_remediation_report   — write Claude's findings to a markdown file

The core pattern is a LOOP:

    ┌─────────────────────────────────────────────────────────────────┐
    │                                                                 │
    │   messages = [initial user message]                             │
    │                                                                 │
    │   LOOP:                                                         │
    │     response = client.messages.create(tools=TOOLS, ...)        │
    │                                                                 │
    │     if stop_reason == "end_turn":                               │
    │         return response.text   ← Claude is done                │
    │                                                                 │
    │     if stop_reason == "tool_use":                               │
    │         for each tool_use block in response:                    │
    │             result = run_tool(name, arguments)  ← real Python  │
    │         messages.append(tool_results)                           │
    │         continue loop                                           │
    │                                                                 │
    └─────────────────────────────────────────────────────────────────┘

That's it. No magic, no framework — just a while loop and an API call.

This pattern generalises to any domain: coding agents, research agents,
DevOps agents. Once you understand this loop you understand all of them.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
USAGE (from phase-3/)
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    # Requires:
    #   ANTHROPIC_API_KEY environment variable
    #   drift_report.json generated by 'make drift'
    #   mlruns/ populated by 'make retrain'

    python src/agent/remediation_agent.py \\
        --report reports/drift_report.json \\
        --data   data/telco_churn.csv

    # Or simpler:
    make agent           # run agent on existing drift report
    make agent-retrain   # generate drift report + run agent in one command
"""
