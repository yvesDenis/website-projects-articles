# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# SYSTEM PROMPT
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
#
# The system prompt defines Claude's role, decision framework, and output format.
# It answers the question: "Given that drift was detected, what should you do?"
#
# Good system prompts are:
#   - Specific about thresholds and decision criteria (not vague platitudes)
#   - Explicit about the order tools should be called
#   - Clear about what the final output should look like
#
SYSTEM_PROMPT = """You are an MLOps remediation agent for a retail customer churn prediction model.

Your task: read the drift report, assess severity, decide on action, and document your reasoning.

## Step-by-step decision framework

1. Call get_drift_summary to understand what drifted and how much.

2. Call get_current_model_metrics to get the baseline before taking any action.

3. Decide whether to retrain:
   - drift_share < 0.20  → no retraining needed; drift is mild
   - drift_share 0.20–0.40 → retraining is worth evaluating
   - drift_share > 0.40  → retraining is recommended

4. If retraining: choose hyperparameters based on WHICH features drifted.
   - Mainly NUMERICAL features drifted (tenure, MonthlyCharges, TotalCharges):
     → Increase n_estimators to 200–300. More trees generalise better when
       continuous distributions shift.
   - Mainly CATEGORICAL features drifted (Contract, PaymentMethod, InternetService):
     → Increase max_depth to 10–12. Deeper trees capture new category patterns.
   - Both types drifted heavily:
     → Start with n_estimators=200, max_depth=10.
   - Never go below n_estimators=50 or max_depth=4 (model becomes too simple).

5. Evaluate the result: the new model must achieve ROC-AUC >= 0.78.
   - If training fails, adjust hyperparameters and try again (max 2 retries).
   - If the new model is WORSE than the baseline, recommend keeping the current one.

6. Call save_remediation_report with your complete findings. The report must
   have these sections in markdown:

   ## Drift Analysis
   ## Baseline Model Performance
   ## Decision & Reasoning
   ## Result (if you retrained)
   ## Recommendation

Be concise and data-driven. Every claim must be backed by numbers from the tool results."""


# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# TOOL DISPATCHER
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def _dispatch_tool(
    tool_name:  str,
    tool_input: dict,
    data_path:  str,
    models_dir: str,
) -> dict:
    """
    Route a tool_use request from Claude to the matching Python function.

    This is the bridge between Claude's DECISION (a JSON object like
    {"name": "run_training", "input": {"n_estimators": 200, "max_depth": 10}})
    and the REAL ACTION (actually running train.py).

    The function name must exactly match the "name" field in TOOLS above,
    and the implementation must exactly match the function in tools.py.
    """
    if tool_name == "get_drift_summary":
        return agent_tools.get_drift_summary(
            report_path=tool_input["report_path"],
        )

    elif tool_name == "get_current_model_metrics":
        return agent_tools.get_current_model_metrics()

    elif tool_name == "run_training":
        return agent_tools.run_training(
            n_estimators=tool_input["n_estimators"],
            max_depth=tool_input["max_depth"],
            data_path=tool_input.get("data_path", data_path),
            models_dir=models_dir,
        )

    elif tool_name == "save_remediation_report":
        return agent_tools.save_remediation_report(
            content=tool_input["content"],
            output_path=tool_input.get("output_path", "reports/remediation_report.md"),
        )

    else:
        available = [t["name"] for t in TOOLS]
        return {"error": f"Unknown tool '{tool_name}'. Available: {available}"}


# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# AGENTIC LOOP
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def run_agent(report_path: str, data_path: str, models_dir: str) -> str:
    """
    Run the Claude remediation agent until it reaches a final answer.

    HOW THE LOOP WORKS
    ------------------
    The `messages` list is the agent's memory. It grows with every turn:

        [user message]
        → [user message, Claude response with tool call]
        → [user message, Claude response, tool results]
        → [user message, Claude response, tool results, Claude response with another tool call]
        → ... and so on until Claude returns plain text (stop_reason="end_turn")

    Claude reads the entire history at each turn, so it knows what it already
    tried and can build on previous results.

    STOP CONDITIONS
    ---------------
    - stop_reason="end_turn"  → Claude returned a final text message (done)
    - turn >= MAX_TURNS       → safety valve to prevent infinite loops
    """
    client = anthropic.Anthropic()  # reads ANTHROPIC_API_KEY from environment

    # Seed the conversation with a description of the situation
    user_message = (
        f"Data drift has been detected in the churn prediction model.\n\n"
        f"Drift report: {report_path}\n"
        f"Training data: {data_path}\n\n"
        f"Please investigate the drift, decide on the best remediation action, "
        f"and save a remediation report."
    )

    messages = [{"role": "user", "content": user_message}]

    print()
    print("=" * 64)
    print("  Claude MLOps Remediation Agent")
    print("=" * 64)

    MAX_TURNS = 10
    turn = 0

    while turn < MAX_TURNS:
        turn += 1
        print(f"\n[Turn {turn}/{MAX_TURNS}] Sending request to Claude...")

        # ── Ask Claude ───────────────────────────────────────────────────────
        # We pass:
        #   system  — the role definition and decision framework
        #   tools   — the list of actions Claude can choose from
        #   messages — the full conversation history
        #
        # Claude's response is either:
        #   A) text (stop_reason="end_turn")  → agent is done
        #   B) tool calls (stop_reason="tool_use") → we run the tools and loop
        #
        response = client.messages.create(
            model="claude-opus-4-7",
            max_tokens=4096,
            system=SYSTEM_PROMPT,
            tools=TOOLS,
            messages=messages,
        )

        # Append Claude's full response to the conversation history.
        # This is CRITICAL: Claude needs to see its own previous responses
        # to understand context and avoid repeating actions.
        messages.append({"role": "assistant", "content": response.content})

        # Print Claude's visible thinking and tool calls so you can follow along
        for block in response.content:
            if hasattr(block, "text") and block.text:
                # Claude sometimes writes reasoning text before calling a tool
                print(f"\n  Claude: {block.text[:400]}{'...' if len(block.text) > 400 else ''}")
            elif block.type == "tool_use":
                args_preview = json.dumps(block.input)[:200]
                print(f"\n  Claude → tool call: {block.name}({args_preview})")

        # ── Terminal condition ────────────────────────────────────────────────
        if response.stop_reason == "end_turn":
            final_text = next(
                (b.text for b in response.content if hasattr(b, "text") and b.text),
                "(No summary text returned.)",
            )
            print("\n" + "=" * 64)
            print("  Agent complete.")
            print("=" * 64)
            return final_text

        # ── Tool execution ────────────────────────────────────────────────────
        # stop_reason="tool_use" means Claude wants to run one or more tools.
        # We execute each tool and build a list of tool_result messages to
        # send back. Claude reads these results in the NEXT turn.
        if response.stop_reason == "tool_use":
            tool_results = []

            for block in response.content:
                if block.type != "tool_use":
                    continue

                print(f"\n  Executing {block.name}...")
                result = _dispatch_tool(block.name, block.input, data_path, models_dir)

                # Show a preview of the result so you can see what Claude receives
                result_str = json.dumps(result, indent=2, default=str)
                preview    = result_str[:600] + ("..." if len(result_str) > 600 else "")
                print(f"  Result:\n{preview}")

                # The tool_result structure is an Anthropic API requirement:
                # each result must reference the tool_use block's ID so Claude
                # can match results to the calls it made.
                tool_results.append({
                    "type":        "tool_result",
                    "tool_use_id": block.id,
                    "content":     result_str,
                })

            # Feed all tool results back to Claude as a "user" turn.
            # This is how the Anthropic API models tool results — they arrive
            # in a user turn, not an assistant turn.
            messages.append({"role": "user", "content": tool_results})

    # Safety: we hit MAX_TURNS without a final "end_turn" response
    print(f"\n[WARN] Agent stopped after {MAX_TURNS} turns without a final response.")
    return f"Agent stopped after {MAX_TURNS} turns. Check reports/ for partial output."


