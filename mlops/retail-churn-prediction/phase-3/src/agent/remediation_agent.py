# CLI
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Claude MLOps remediation agent — analyzes drift and decides on action."
    )
    parser.add_argument(
        "--report",
        required=True,
        help="Path to drift_report.json (generated by 'make drift')",
    )
    parser.add_argument(
        "--data",
        required=True,
        help="Path to the training CSV (e.g. data/telco_churn.csv)",
    )
    parser.add_argument(
        "--models-dir",
        default="models/",
        help="Directory containing model.pkl and preprocessor.pkl",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    # Pre-flight checks: fail fast with a clear message instead of a confusing traceback
    if not os.path.exists(args.report):
        print(f"ERROR: Drift report not found at '{args.report}'.")
        print("       Run 'make drift' first to generate it.")
        sys.exit(1)

    if not os.environ.get("ANTHROPIC_API_KEY"):
        print("ERROR: ANTHROPIC_API_KEY environment variable is not set.")
        print("       Get your key at https://console.anthropic.com and set it with:")
        print("       export ANTHROPIC_API_KEY=sk-ant-...")
        sys.exit(1)

    # Run the agent — this may take a minute or two if it decides to retrain
    summary = run_agent(
        report_path=args.report,
        data_path=args.data,
        models_dir=args.models_dir,
    )

    print(f"\nAgent summary:\n{summary}")


if __name__ == "__main__":
    main()
